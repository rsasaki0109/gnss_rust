//! Physical constants from libgnss++ `core/constants.hpp`.

pub const SPEED_OF_LIGHT: f64 = 299_792_458.0;
pub const OMEGA_E: f64 = 7.292_115_146_7e-5;
pub const GPS_L1_FREQ: f64 = 1575.42e6;
pub const GPS_L2_FREQ: f64 = 1227.60e6;
pub const GPS_L5_FREQ: f64 = 1176.45e6;
pub const GLO_L1_BASE_FREQ: f64 = 1602.0e6;
pub const GLO_L1_STEP_FREQ: f64 = 0.5625e6;
pub const GLO_L2_BASE_FREQ: f64 = 1246.0e6;
pub const GLO_L2_STEP_FREQ: f64 = 0.4375e6;
pub const GAL_E1_FREQ: f64 = 1575.42e6;
pub const GAL_E5A_FREQ: f64 = 1176.45e6;
pub const GAL_E5B_FREQ: f64 = 1207.14e6;
pub const GAL_E6_FREQ: f64 = 1278.75e6;
pub const BDS_B1I_FREQ: f64 = 1561.098e6;
pub const BDS_B2I_FREQ: f64 = 1207.14e6;
pub const BDS_B3I_FREQ: f64 = 1268.52e6;
pub const BDS_B1C_FREQ: f64 = 1575.42e6;
pub const BDS_B2A_FREQ: f64 = 1176.45e6;

pub const GPS_L1_WAVELENGTH: f64 = SPEED_OF_LIGHT / GPS_L1_FREQ;
pub const GPS_L2_WAVELENGTH: f64 = SPEED_OF_LIGHT / GPS_L2_FREQ;
pub const GPS_L5_WAVELENGTH: f64 = SPEED_OF_LIGHT / GPS_L5_FREQ;
pub const GAL_E1_WAVELENGTH: f64 = SPEED_OF_LIGHT / GAL_E1_FREQ;
pub const GAL_E5A_WAVELENGTH: f64 = SPEED_OF_LIGHT / GAL_E5A_FREQ;
pub const GAL_E5B_WAVELENGTH: f64 = SPEED_OF_LIGHT / GAL_E5B_FREQ;
pub const GAL_E6_WAVELENGTH: f64 = SPEED_OF_LIGHT / GAL_E6_FREQ;
pub const BDS_B1I_WAVELENGTH: f64 = SPEED_OF_LIGHT / BDS_B1I_FREQ;
pub const BDS_B2I_WAVELENGTH: f64 = SPEED_OF_LIGHT / BDS_B2I_FREQ;
pub const BDS_B3I_WAVELENGTH: f64 = SPEED_OF_LIGHT / BDS_B3I_FREQ;
pub const BDS_B1C_WAVELENGTH: f64 = SPEED_OF_LIGHT / BDS_B1C_FREQ;
pub const BDS_B2A_WAVELENGTH: f64 = SPEED_OF_LIGHT / BDS_B2A_FREQ;

pub const WGS84_A: f64 = 6_378_137.0;
pub const WGS84_F: f64 = 1.0 / 298.257_223_563;
pub const WGS84_B: f64 = WGS84_A * (1.0 - WGS84_F);
pub const WGS84_E2: f64 = 2.0 * WGS84_F - WGS84_F * WGS84_F;
pub const SECONDS_PER_WEEK: f64 = 604_800.0;
/// Unix timestamp of 1980-01-06 00:00:00, the GPS epoch label.
pub const GPS_EPOCH_UNIX_SECONDS: u64 = 315_964_800;

pub const IFLC_C1: f64 = GPS_L2_WAVELENGTH * GPS_L2_WAVELENGTH
    / (GPS_L2_WAVELENGTH * GPS_L2_WAVELENGTH - GPS_L1_WAVELENGTH * GPS_L1_WAVELENGTH);
pub const IFLC_C2: f64 = -GPS_L1_WAVELENGTH * GPS_L1_WAVELENGTH
    / (GPS_L2_WAVELENGTH * GPS_L2_WAVELENGTH - GPS_L1_WAVELENGTH * GPS_L1_WAVELENGTH);
pub const IFLC_F1: f64 =
    GPS_L1_FREQ * GPS_L1_FREQ / (GPS_L1_FREQ * GPS_L1_FREQ - GPS_L2_FREQ * GPS_L2_FREQ);
pub const IFLC_F2: f64 =
    -GPS_L2_FREQ * GPS_L2_FREQ / (GPS_L1_FREQ * GPS_L1_FREQ - GPS_L2_FREQ * GPS_L2_FREQ);
pub const GPS_WL_WAVELENGTH: f64 = SPEED_OF_LIGHT / (GPS_L1_FREQ - GPS_L2_FREQ);
pub const GPS_NL_WAVELENGTH: f64 = IFLC_F1 * GPS_L1_WAVELENGTH + IFLC_F2 * GPS_L2_WAVELENGTH;
