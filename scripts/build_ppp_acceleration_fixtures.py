"""Build unchanged native PVA component/physics fixtures and reproduce them twice."""
import argparse
import gzip
import hashlib
import json
import os
from pathlib import Path
import subprocess


def sha(p):
    with Path(p).open('rb') as f:return hashlib.file_digest(f,'sha256').hexdigest()


def main():
    p=argparse.ArgumentParser(description=__doc__);p.add_argument('--output-dir',type=Path,required=True);p.add_argument('--update-fixtures',action='store_true',help='replace generated fixtures after saving old bytes in the output directory');a=p.parse_args();repo=Path(__file__).resolve().parents[1];out=a.output_dir.resolve();out.mkdir(parents=True,exist_ok=False)
    prior=repo/'docs/comparison/2026-10-21-ppc-ppp-first/native-initial.json';old=json.loads(prior.read_text());libs=old['native_library_sha256'];assert all(sha(f)==h for f,h in libs.items())
    binary=out/'native';source=repo/'scripts/upstream_ppp_acceleration.cpp';command=['g++','-std=c++17','-O2','-Wall','-Wextra','-Werror','-I/workspace/.cloud-setup/reference/gnssplusplus-library/include','-I/workspace/.cloud-setup/reference/gnssplusplus-library/src/core','-I/workspace/.cloud-setup/eigen-3.4.0',str(source),'-Wl,--start-group']+list(libs)+['-Wl,--end-group','-o',str(binary)]
    r=subprocess.run(command,stdout=subprocess.PIPE,stderr=subprocess.STDOUT);(out/'build.log.gz').write_bytes(gzip.compress(r.stdout,mtime=0))
    sources=[source]+[repo/'scripts'/f for f in ['upstream_precise_transmit.cpp','upstream_precise.cpp','upstream_navigation.cpp','build_ppp_acceleration_fixtures.py']]
    dataset=Path('/workspace/.cloud-setup/datasets/PPC-Dataset');inputs=[repo/'tests/fixtures'/f for f in ['synthetic_ppp.sp3','synthetic_ppp.clk']]+[dataset/city/run/'rover.obs' for city in ['nagoya','tokyo'] for run in ['run1','run2','run3']]
    manifest=dict(command=command,returncode=r.returncode,source_sha256={str(f.relative_to(repo)):sha(f) for f in sources},input_sha256={str(f):sha(f) for f in inputs},native_library_sha256=libs,pinned_upstream_commit=old['upstream_commit'],source_archive_sha256=old['source_archive_sha256'],prior_proof=str(prior.relative_to(repo)),prior_proof_sha256=sha(prior),upstream_source_patched=False,whole_native_PPP_executed=False,actual_PVA_prediction_calls_per_repeat=48,actual_PVA_initialization_calls_per_repeat=54,explicit_PPC_header_initializations_per_repeat=6,GNSS_environment_removed=sorted(k for k in os.environ if k.startswith('GNSS_')),repeat_runs=[])
    def save():(out/'native-generator.json').write_text(json.dumps(manifest,indent=2)+'\n')
    save();print('Build',r.returncode,flush=True)
    if r.returncode:print(r.stdout.decode());raise SystemExit(r.returncode)
    manifest['binary_sha256']=sha(binary);manifest['compiler']=subprocess.check_output(['g++','--version'],text=True).splitlines()[0]
    env={k:v for k,v in os.environ.items() if not k.startswith('GNSS_')}
    for repeat in range(2):
        target=out/str(repeat);target.mkdir();cmd=[str(binary),str(repo/'tests/fixtures'),str(dataset),str(target)];r=subprocess.run(cmd,capture_output=True,env=env);(out/f'run{repeat}.stdout.log.gz').write_bytes(gzip.compress(r.stdout,mtime=0));(out/f'run{repeat}.stderr.log.gz').write_bytes(gzip.compress(r.stderr,mtime=0));assert r.returncode==0,r.stderr.decode()
        files={f.name:sha(f) for f in sorted(target.iterdir())};manifest['repeat_runs'].append(dict(command=cmd,returncode=0,fixture_sha256=files));save();print('Generation',repeat,'passed',flush=True)
    assert manifest['repeat_runs'][0]['fixture_sha256']==manifest['repeat_runs'][1]['fixture_sha256']
    for name,h in manifest['repeat_runs'][0]['fixture_sha256'].items():
        dest=repo/'tests/fixtures'/name
        if dest.exists() and sha(dest)!=h:
            assert a.update_fixtures,'use --update-fixtures to preserve and replace old generated bytes'
            previous=out/'previous-fixtures';previous.mkdir(exist_ok=True);(previous/name).write_bytes(dest.read_bytes());dest.write_bytes((out/'0'/name).read_bytes())
        elif dest.exists():assert sha(dest)==h
        else:
            with dest.open('xb') as f:f.write((out/'0'/name).read_bytes())
        print(name,flush=True)
    assert all(sha(f)==h for f,h in manifest['input_sha256'].items())


if __name__=='__main__':main()
